"""Generate desktop_studio/src/icons_lucide.h from the Lucide icon font's info.json (lucide-static package, ISC).

    py desktop_studio/tools/gen_icons_lucide.py <lucide-static>/font/info.json

Only the icons listed in ICONS are emitted, plus ICON_LC_RANGES (the glyph ranges to bake into the ImGui atlas, so the
atlas holds those glyphs only). The font file itself is desktop_studio/assets/fonts/lucide.ttf (lucide-static 0.460.0).
Our own code (MIT).
"""
import json
import pathlib
import sys

ICONS = """mouse-pointer-2 move paintbrush flip-horizontal-2 undo-2 redo-2 trash-2 copy scissors bone box play pause square
step-forward wind activity person-standing sun sunrise sunset moon contrast scan search chevron-down chevron-right
chevron-left chevron-up check circle-check triangle-alert info package save folder folder-open users palette sparkles
clock git-branch history refresh-cw filter image keyboard settings cpu mouse x plus ellipsis arrow-right layers user
cloud flame camera brush eye rotate-3d terminal grip-vertical crosshair spline""".split()


def main():
    info = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
    missing = [n for n in ICONS if n not in info]
    if missing:
        sys.exit(f"missing icons: {missing}")
    lines = ["// Generated by desktop_studio/tools/gen_icons_lucide.py from lucide-static 0.460.0 font/info.json.",
             "// Lucide icons: ISC licence (assets/fonts/LICENSE_lucide.txt). Do not edit by hand.", "#pragma once", ""]
    cps = []
    for n in ICONS:
        cp = int(info[n]["encodedCode"].lstrip("\\"), 16)
        cps.append(cp)
        u = chr(cp).encode("utf-8")
        esc = "".join(f"\\x{b:02x}" for b in u)
        lines.append(f'#define ICON_LC_{n.upper().replace("-", "_")} "{esc}"')
    cps.sort()
    ranges = []
    for cp in cps:
        if ranges and ranges[-1][1] + 1 == cp:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    flat = ", ".join(f"0x{a:04X}, 0x{b:04X}" for a, b in ranges)
    lines += ["", "// glyph ranges (pairs, zero-terminated) for ImFontAtlas::AddFontFromFileTTF",
              f"#define ICON_LC_RANGES {{{flat}, 0}}", ""]
    out = pathlib.Path(__file__).resolve().parents[1] / "src" / "icons_lucide.h"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{out}: {len(ICONS)} icons, {len(ranges)} ranges")


if __name__ == "__main__":
    main()
